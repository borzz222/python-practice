n = int(input())
length = 1  # сколько цифр в каждом числе текущей группы
count = 9   # сколько чисел в текущей группе
start = 1   # первое число текущей группы

# length * count - сколько всего цифр занимает группа.
while n > length * count:
    n -= length * count  # вычитаем цифры пропущенной группы
    length += 1          # следующая группа: числа на 1 цифру длиннее,
    count *= 10          # чисел в ней в 10 раз больше,
    start *= 10          # и начинается она с числа в 10 раз больше

#Теперь n - номер цифры внутри найденной группы.
# (n - 1) - индекс с нуля; каждое число занимает length цифр, поэтому:
# (n - 1) // length - сколько целых чисел группы стоит перед нужным,
# (n - 1) % length  - индекс нужной цифры внутри числа.
num = start + (n - 1) // length
print(str(num)[(n - 1) % length])